// Builds the RouterOS 7 script that makes a MikroTik with GPS (e.g. LtAP) report its position. Client-safe.

export type MikrotikOptions = { url: string; token: string; vehicleId: string; intervalSeconds: number };

const SCRIPT_NAME = "cartracker-report";

// Escapes text for a double-quoted RouterOS string; "?" must be escaped or the terminal shows help.
function routerosLiteral(text: string): string {
  return text.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$").replace(/\?/g, "\\?");
}

function reportScript({ url, token, vehicleId }: MikrotikOptions): string {
  return [
    "# Sends the current GPS position to CarTracker. Generated by CarTracker.",
    `:local url "${routerosLiteral(url)}"`,
    `:local token "${routerosLiteral(token)}"`,
    `:local vehicle "${routerosLiteral(vehicleId)}"`,
    "",
    '# Keeps the leading number of a GPS value, e.g. "54.3 km/h" -> 54.3; "none" -> 0.',
    ":local num do={",
    "  :local s [:tostr $1]",
    '  :local out ""',
    "  :local done false",
    "  :for i from=0 to=([:len $s] - 1) do={",
    "    :local c [:pick $s $i]",
    "    :if (!$done) do={",
    '      :if ([:typeof [:find "0123456789.-" $c]] = "num") do={ :set out ($out . $c) } else={ :if ([:len $out] > 0) do={ :set done true } }',
    "    }",
    "  }",
    '  :if ([:len $out] = 0) do={ :return "0" }',
    "  :return $out",
    "}",
    "",
    ":local gps [/system gps monitor once as-value]",
    ':if (($gps->"valid") != true) do={',
    '  :log debug "CarTracker: no GPS fix yet"',
    "} else={",
    '  :local json ("{\\"vehicleId\\":\\"" . $vehicle . "\\"" . ",\\"latitude\\":" . [$num ($gps->"latitude")] . ",\\"longitude\\":" . [$num ($gps->"longitude")] . ",\\"speed\\":" . [$num ($gps->"speed")] . ",\\"heading\\":" . [$num ($gps->"true-bearing")] . ",\\"altitude\\":" . [$num ($gps->"altitude")] . ",\\"satellites\\":" . [$num ($gps->"satellites")] . ",\\"fixQuality\\":" . [$num ($gps->"fix-quality")] . ",\\"accuracy\\":" . [$num ($gps->"horizontal-dilution")] . "}")',
    "  :do {",
    '    /tool fetch url=$url http-method=post output=none check-certificate=no http-header-field=("Authorization: Bearer " . $token . ",Content-Type: application/json") http-data=$json',
    '  } on-error={ :log warning "CarTracker: could not send position" }',
    "}",
  ].join("\n");
}

// The whole script goes inside source="...", so it's escaped once more, with line breaks as \r\n.
function routerosString(text: string): string {
  return routerosLiteral(text).replace(/\n/g, "\\r\\n");
}

/** Readable script (for System > Scripts) and a single paste-in-terminal install command. */
export function buildMikrotikScript(options: MikrotikOptions): { script: string; install: string } {
  const script = reportScript(options);
  const install = [
    "/system gps set enabled=yes coordinate-format=dd",
    `/system script remove [find name="${SCRIPT_NAME}"]`,
    `/system script add name="${SCRIPT_NAME}" policy=read,write,test dont-require-permissions=yes source="${routerosString(script)}"`,
    `/system scheduler remove [find name="${SCRIPT_NAME}"]`,
    `/system scheduler add name="${SCRIPT_NAME}" interval=${options.intervalSeconds}s start-time=startup on-event="/system script run ${SCRIPT_NAME}"`,
  ].join("\n");
  return { script, install };
}
